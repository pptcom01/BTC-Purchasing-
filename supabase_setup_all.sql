-- วิธีใช้: Supabase Dashboard > SQL Editor > New query > วางทั้งหมดนี้ > Run
-- ข้อดี: รันซ้ำกี่รอบก็ได้ (idempotent — ไม่พังไม่ซ้ำซ้อน) เหมาะสำหรับ
--        "อัปเดต/ปรับปรุง" ในอนาคต — แก้ไฟล์นี้ไฟล์เดียว แล้วรันซ้ำ = schema สดเสมอ
