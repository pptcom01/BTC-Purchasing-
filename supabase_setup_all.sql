-- RPC: หาแม่แบบที่ match (rule-based: doc_type คุมหลัก + hamming distance เรียง + usage)
CREATE OR REPLACE FUNCTION public.find_matching_templates(
  p_doc_type text,
  p_signature text,
  p_threshold integer DEFAULT 10,
  p_limit integer DEFAULT 3
)
RETURNS SETOF public.ai_templates
LANGUAGE plpgsql STABLE AS $$
DECLARE sigEmpty boolean;
BEGIN
  sigEmpty := (p_signature IS NULL OR p_signature = '');
  RETURN QUERY
  SELECT t.*
  FROM public.ai_templates t
  WHERE t.status = 'active' AND t.doc_type = p_doc_type
  ORDER BY
    (CASE WHEN sigEmpty OR t.layout_signature IS NULL OR t.layout_signature = ''
          THEN 0 ELSE hamming_distance(t.layout_signature, p_signature) END),
    t.usage_count DESC
  LIMIT p_limit;
END $$;

-- RPC: Hamming distance สำหรับ layout hash (รับ "aHash:32x32:<16hex>" หรือ "<16hex>" — เทียบ 16 หลักท้าย)
CREATE OR REPLACE FUNCTION public.hamming_distance(hex1 text, hex2 text)
RETURNS integer
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  h1 text; h2 text; b1 bit(64); b2 bit(64); diff bit(64);
  cnt integer := 0; i integer;
BEGIN
  h1 := trim(right(coalesce(hex1, ''), 16));
  h2 := trim(right(coalesce(hex2, ''), 16));
  IF h1 = '' OR h2 = '' OR h1 !~ '^[0-9a-fA-F]{16}$' OR h2 !~ '^[0-9a-fA-F]{16}$' THEN
    RETURN 999;
  END IF;
  b1 := decode(h1, 'hex')::bit(64);
  b2 := decode(h2, 'hex')::bit(64);
  diff := b1 # b2;
  FOR i IN 0..63 LOOP
    IF diff[i] = 1 THEN cnt := cnt + 1; END IF;
  END LOOP;
  RETURN cnt;
END $$;

