--   [10] ตาราง ai_prompts: ชุด prompt AI ต่อประเภท "AI เขียนเอง" Phase 2
--        + migration: ai_templates.doc_type → predicted_doc_type แล้ว doc_type=NULL
--   [11] ตาราง ai_feedback_logs: Human-in-the-Loop (AI Active Learning)
--   [12] ตาราง vendor_billing: ใบวางบิล + รายการผูกบิล
--   [13] receipts: เลขที่รายการของระบบ (System Record No.) — รันต่อเนื่องห้ามซ้ำ + สร้างย้อนหลังเอกสารเก่า
--   [7] ตรวจผลรวมทุกส่วนท้ายไฟล์ (รวมส่วน AI)
--   [8] SELF-HEAL: ให้สิทธิ์ซ้ำทุกครั้งที่รัน (ครอบคลุม doc_types / receipt_learning / views ธุรกิจ ด้วย) + รายงาน 1 แถว
--
-- หมายเหตุ: ถ้าอยากรู้ว่าส่วนไหนทำอะไร อ่าน block ตามหมายเลขได้เลย
--           ส่วนที่รันแล้วจะ "ข้าม" อย่างปลอดภัย (IF NOT EXISTS / IF EXISTS)
--           รันครั้งไหนมี error ตัวแดง = เอาเฉพาะข้อความแดงนั้นมาแจ้ง (ที่เหลือน่าจะผ่านหมด)
-- ============================================================

