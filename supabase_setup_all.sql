-- atomic sequential counter (แถวเดียว + FOR UPDATE = จองเลขแบบมือเดียว ไม่ซ้ำดุเดือด)
CREATE TABLE IF NOT EXISTS public.running_number_counter (
  id smallint PRIMARY KEY CHECK (id = 1),
  last_month text NOT NULL DEFAULT '',
  last_no bigint NOT NULL DEFAULT 0
);

-- RPC จองเลข TR เดือนถัดไป: row lock → เลขถัดไป ไม่ต้องรอ JavaScript math ฝั่ง GAS
CREATE OR REPLACE FUNCTION public.next_running_number(p_month text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_last text;
  v_no bigint;
BEGIN
  INSERT INTO public.running_number_counter (id, last_month, last_no) VALUES (1, '', 0)
  ON CONFLICT (id) DO NOTHING;
  SELECT last_month, last_no INTO v_last, v_no FROM public.running_number_counter WHERE id = 1 FOR UPDATE;
  IF COALESCE(v_last, '') = p_month THEN
    v_no := v_no + 1;
  ELSE
    v_last := p_month;
    v_no := 1;
  END IF;
  UPDATE public.running_number_counter SET last_month = v_last, last_no = v_no WHERE id = 1;
  RETURN 'TR-' || p_month || '-' || lpad(v_no::text, 5, '0');
END;
$$;

-- RPC ซิงก์ counter ให้สอดคล้องกับเลข TR ที่ backfill ไปแล้วของเดือนปัจจุบัน (กันชนกับเลขเก่า)
CREATE OR REPLACE FUNCTION public.sync_running_number_counter()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_month text := to_char(now() AT TIME ZONE 'Asia/Bangkok', 'YYYYMM');
  v_max bigint;
BEGIN
  INSERT INTO public.running_number_counter (id, last_month, last_no) VALUES (1, '', 0)
  ON CONFLICT (id) DO NOTHING;
  SELECT COALESCE(max((regexp_split_to_array(running_number, '-'))[3]::bigint), 0) INTO v_max
  FROM public.receipts
  WHERE running_number IS NOT NULL AND running_number LIKE 'TR-' || v_month || '-%';
  UPDATE public.running_number_counter
     SET last_month = v_month, last_no = GREATEST(COALESCE(last_no, 0), v_max)
   WHERE id = 1;
END;
$$;

-- มือที่จองเลขได้ = เฉพาะ GAS/webhook (service_role) — หน้าเว็บ/anon จองเองไม่ได้
REVOKE ALL ON FUNCTION public.next_running_number(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.next_running_number(text) TO service_role;
REVOKE ALL ON FUNCTION public.sync_running_number_counter() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.sync_running_number_counter() TO service_role;

-- backfill: ใส่ TR ให้แถวเก่าที่ยังว่าง (เรียง created_at เดือนละเดือน → ได้ตัวเลขเดิมทุกครั้งที่รันซ้ำ)
-- หมายเหตุ: ใช้ COALESCE(created_at, submitted_at) — เพราะบิลเก่าบางชุด submitted_at เป็น NULL (บันทึกไม่ลงค่า)
--          created_at = ตอนที่ระบบรับบิลเข้า DB (default now()) มีค่าเสมอ
WITH numbered AS (
  SELECT ctid,
         'TR-' || to_char(COALESCE(created_at, submitted_at) AT TIME ZONE 'Asia/Bangkok', 'YYYYMM') || '-' ||
         lpad((row_number() OVER (PARTITION BY to_char(COALESCE(created_at, submitted_at) AT TIME ZONE 'Asia/Bangkok', 'YYYYMM')
                                   ORDER BY COALESCE(created_at, submitted_at) ASC, ctid))::text, 5, '0') AS rn
  FROM public.receipts
  WHERE running_number IS NULL
)
UPDATE public.receipts r SET running_number = n.rn
FROM numbered n WHERE r.ctid = n.ctid;

SELECT public.sync_running_number_counter();

-- รายงานผล TR 5 ใบล่าสุด + counter (ถ้าได้ตัวเลข TR-YYYYMM-xxxxx = พร้อมใช้)
SELECT running_number, system_record_no, doc_key
FROM public.receipts
WHERE running_number IS NOT NULL
ORDER BY created_at DESC
LIMIT 5;

SELECT last_month, last_no FROM public.running_number_counter;

